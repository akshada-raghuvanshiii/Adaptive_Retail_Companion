#!/usr/bin/env bash
# ARC compact store installer. DRY RUN unless --apply is given.
#
#   ./install.sh                          # dry run: verify, generate, remap, show diffs
#   ./install.sh --keep-model mannequin   # keep a model from your old world (repeatable)
#   ./install.sh --apply                  # back up originals, then install
#   ./install.sh --ws ~/other_ws          # different workspace (default ~/slam_ws)
#
# What --apply changes (everything is backed up first, restore with the printed RESTORE.sh):
#   REPLACE  arc_store_sim/worlds/arc_store.sdf            (new compact world, your world-level settings kept)
#   REPLACE  arc_store_sim/config/item_locations.yaml      (same items/IDs/categories, new map-frame poses)
#   ADD      arc_store_sim/worlds/arc_store_compact.sdf    (same world, explicit name)
#   ADD      arc_store_sim/config/store_layout_compact.json, destinations_map.yaml
#   ADD      arc_store_sim/scripts/compact_store/          (this kit, so the world can be regenerated)
#   ADD+PATCH arc_planner/.../goal_frame_guard.py + 2 lines of dijkstra_planner.py, ONLY if the planner
#            has no goal-frame guard of its own (yours already has one: then nothing is changed there)
#   PATCH    arc_planner/arc_planner/shopping_manager.py   (frame literal 'world' -> 'map', if present)
# Not touched: store_layout.json, generate_store.py, launch files, RTAB-Map config, controller,
# TEB bridge, arc_motion_gate, Behavior Tree, robot model.
set -euo pipefail

KIT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
WS="$HOME/slam_ws"
APPLY=0
KEEP=()
while [[ $# -gt 0 ]]; do
  case "$1" in
    --apply) APPLY=1; shift ;;
    --ws) WS="$2"; shift 2 ;;
    --keep-model) KEEP+=(--keep-model "$2"); shift 2 ;;
    --add-model) KEEP+=(--add-model "$2"); shift 2 ;;
    --place) KEEP+=(--place "$2"); shift 2 ;;
    -h|--help) sed -n '2,22p' "$0"; exit 0 ;;
    *) echo "unknown option $1"; exit 2 ;;
  esac
done
WS="$(cd "$WS" && pwd)"
PKG="$WS/src/arc_store_sim"
PLN="$WS/src/arc_planner/arc_planner"
WORLD="$PKG/worlds/arc_store.sdf"
ITEMS="$PKG/config/item_locations.yaml"
LAYOUT="$PKG/config/store_layout.json"
GEN="$PKG/scripts/generate_store.py"
SM="$PLN/shopping_manager.py"
DJ="$PLN/dijkstra_planner.py"
STAGE="$KIT/staged"

say() { printf '\n== %s\n' "$*"; }
need_python() { python3 -c "import yaml" 2>/dev/null || { echo "python3-yaml missing: sudo apt install python3-yaml"; exit 1; }; }

say "Checking files in $WS"
missing=0
for f in "$WORLD" "$ITEMS" "$DJ"; do
  if [[ -f "$f" ]]; then echo "  found    $f"; else echo "  MISSING  $f  (required)"; missing=1; fi
done
for f in "$LAYOUT" "$GEN" "$SM"; do
  if [[ -f "$f" ]]; then echo "  found    $f"; else echo "  missing  $f  (optional)"; fi
done
[[ $missing -eq 0 ]] || { echo "Required files missing; nothing done."; exit 1; }
need_python

# Template world + source items. If arc_store.sdf was already generated by this kit (a previous
# install), regenerate from YOUR ORIGINAL store instead: the oldest backup that is not generated.
MARK="Generated by arc_compact_store_kit"
SRC_WORLD="$WORLD"; SRC_ITEMS="$ITEMS"
if grep -q "$MARK" "$WORLD"; then
  echo "  arc_store.sdf is already a compact store from an earlier install; looking for your original"
  for b in $(ls -d "$WS"/arc_backups/compact_store_* 2>/dev/null | sort); do
    bw="$b$WORLD"; bi="$b$ITEMS"
    if [[ -f "$bw" && -f "$bi" ]] && ! grep -q "$MARK" "$bw"; then SRC_WORLD="$bw"; SRC_ITEMS="$bi"; break; fi
  done
  if [[ "$SRC_WORLD" == "$WORLD" ]]; then
    echo "  REFUSED: no backup of the original world found in $WS/arc_backups; nothing done."; exit 1
  fi
  echo "  using original world: $SRC_WORLD"
  echo "  using original items: $SRC_ITEMS"
fi

say "1/5 Verifying the compact layout geometry"
( cd "$KIT" && python3 verify_layout.py --json "$KIT/output/layout_verification.json" ) | tail -3

say "2/5 Generating the world from your existing world's settings"
( cd "$KIT" && python3 generate_compact_store.py --list-template --template "$SRC_WORLD" )
mkdir -p "$STAGE"
( cd "$KIT" && python3 generate_compact_store.py --out-dir "$STAGE" --template "$SRC_WORLD" "${KEEP[@]}" )

say "3/5 Remapping your item_locations.yaml (IDs and categories kept)"
( cd "$KIT" && python3 remap_item_locations.py "$SRC_ITEMS" --write --out "$STAGE/item_locations.yaml" \
    --report "$STAGE/item_remap_report.csv" )

say "4/5 Code patches (preview)"
( cd "$KIT" && python3 apply_patches.py --ws "$WS" ) || echo "  (a patch was skipped: see above; install continues, apply that change by hand per RUNBOOK)"

say "5/5 Looking for anything that would regenerate the OLD store automatically"
# Only places that EXECUTE at launch/build time matter (not READMEs, tests or comments).
if grep -rnI --include="*.launch.py" --include="CMakeLists.txt" --include="setup.py" "generate_store" "$PKG" "$WS/src/arc_planner" 2>/dev/null; then
  echo "  ^ WARNING: these reference generate_store.py. If a launch/build step runs it, it will overwrite"
  echo "    arc_store.sdf with the old store. Disable that step, or point it at scripts/compact_store."
else
  echo "  none found"
fi

if [[ $APPLY -eq 0 ]]; then
  say "DRY RUN complete. Staged files: $STAGE"
  echo "Review: $STAGE/item_remap_report.csv, $KIT/output/layout_preview.png"
  echo "Then run:  $0 --apply ${KEEP[*]:-}"
  exit 0
fi

TS="$(date +%Y%m%d_%H%M%S)"
BK="$WS/arc_backups/compact_store_$TS"
say "Backing up originals to $BK"
mkdir -p "$BK"
ADDED=("$PKG/worlds/arc_store_compact.sdf" "$PKG/config/store_layout_compact.json" "$PKG/config/destinations_map.yaml")
for f in "$WORLD" "$ITEMS" "$LAYOUT" "$GEN" "$SM" "$DJ" "${ADDED[@]}"; do
  if [[ -f "$f" ]]; then cp --parents -p "$f" "$BK/"; fi
done
if [[ -d "$PKG/scripts/compact_store" ]]; then cp -a "$PKG/scripts/compact_store" "$BK/compact_store_dir"; fi
( cd "$BK" && find . -path ./compact_store_dir -prune -o -type f ! -name SHA256SUMS -exec sha256sum {} + > SHA256SUMS )
cat > "$BK/RESTORE.sh" <<EOF
#!/usr/bin/env bash
# Restore the files backed up on $TS and remove the files the compact-store install added.
# A file EDITED AFTER the install (checksum differs from INSTALLED_SUMS and from the backup)
# is NOT overwritten, so later hand edits are never lost silently. --force overwrites anyway.
set -euo pipefail
FORCE=0; [[ "\${1:-}" == "--force" ]] && FORCE=1
cd "$BK"
find . -path ./compact_store_dir -prune -o -type f ! -name SHA256SUMS ! -name RESTORE.sh ! -name INSTALLED_SUMS ! -name added_goal_frame_guard -print | while read -r f; do
  dst="/\${f#./}"
  if [[ \$FORCE -eq 0 && -f "\$dst" && -f INSTALLED_SUMS ]]; then
    inst=\$(grep -F "  \$dst" INSTALLED_SUMS | cut -d' ' -f1 || true)
    now=\$(sha256sum "\$dst" | cut -d' ' -f1); orig=\$(sha256sum "\$f" | cut -d' ' -f1)
    if [[ -n "\$inst" && "\$now" != "\$inst" && "\$now" != "\$orig" ]]; then
      echo "KEPT     \$dst  (edited after the install; RESTORE.sh --force overwrites)"; continue
    fi
  fi
  cp -p "\$f" "\$dst"; echo "restored \$dst"
done
for f in "$PKG/worlds/arc_store_compact.sdf" "$PKG/config/store_layout_compact.json" "$PKG/config/destinations_map.yaml"; do
  if [[ ! -f "$BK\$f" ]]; then rm -f "\$f"; fi    # added by this install (did not exist before)
done
if [[ -f added_goal_frame_guard ]]; then rm -f "$PLN/goal_frame_guard.py"; fi
rm -rf "$PKG/scripts/compact_store"
if [[ -d "$BK/compact_store_dir" ]]; then cp -a "$BK/compact_store_dir" "$PKG/scripts/compact_store"; echo "restored $PKG/scripts/compact_store"; fi
echo "Done. Rebuild: cd $WS && colcon build --packages-select arc_store_sim arc_planner"
EOF
chmod +x "$BK/RESTORE.sh"
echo "  backed up $(($(wc -l < "$BK/SHA256SUMS"))) files; restore with $BK/RESTORE.sh"

say "Installing"
cp "$STAGE/arc_store_compact.sdf" "$WORLD"
cp "$STAGE/arc_store_compact.sdf" "$PKG/worlds/arc_store_compact.sdf"
cp "$STAGE/item_locations.yaml" "$ITEMS"
cp "$STAGE/store_layout_compact.json" "$PKG/config/store_layout_compact.json"
cp "$STAGE/destinations_map.yaml" "$PKG/config/destinations_map.yaml"
if python3 -c "import sys; sys.path.insert(0, '$KIT'); import apply_patches as a; s=open('$DJ').read(); sys.exit(0 if (a.GUARD_MARK in s or a.has_equivalent_guard(s)) else 1)"; then
  echo "  planner already guards goal frames: goal_frame_guard.py not copied"
else
  cp "$KIT/arc_planner_addon/goal_frame_guard.py" "$PLN/goal_frame_guard.py"; touch "$BK/added_goal_frame_guard"
fi
mkdir -p "$PKG/scripts/compact_store"
cp -r "$KIT"/{layout.py,generate_compact_store.py,verify_layout.py,remap_item_locations.py,README.md,RUNBOOK.md,RUN.md,ros_tools,run} \
      "$PKG/scripts/compact_store/"
( cd "$KIT" && python3 apply_patches.py --ws "$WS" --apply ) || echo "  (a patch was skipped: apply it by hand per RUNBOOK)"

for f in "$WORLD" "$ITEMS" "$LAYOUT" "$GEN" "$SM" "$DJ" "${ADDED[@]}"; do if [[ -f "$f" ]]; then sha256sum "$f"; fi; done > "$BK/INSTALLED_SUMS"

say "Installed. Next: rebuild, then RUN.md"
echo "  cd $WS && colcon build --symlink-install --packages-select arc_store_sim arc_planner && source install/setup.bash"
echo "  Restore everything: $BK/RESTORE.sh"
