#!/usr/bin/env bash
# ARC compact-store launcher: opens every part of the pipeline in its own terminal tab, in order.
#
#   ./arc_up.sh check            pre-flight: files, packages, venv, saved map (changes nothing)
#   ./arc_up.sh map              FIRST TIME (or new store): Gazebo + robot + RTAB-Map (new map) + RViz,
#                                then the autonomous mapping drive; when it finishes the map is backed up
#   ./arc_up.sh nav              every later run: reuses the saved map (localization only, cannot be
#                                corrupted) + full navigation stack + store labels + Shopping Manager
#   ./arc_up.sh nav --perception same, but the camera perception bridge drives the behaviour tree
#                                instead of the person_state_input keyboard menu
#   ./arc_up.sh stop             close every ARC process
#
# Tabs open in gnome-terminal. Without gnome-terminal (or with DRY=1) the commands are printed instead,
# one per terminal, to run by hand. Nothing in ~/slam_ws is modified by this script.
set -uo pipefail

WS="${WS:-$HOME/slam_ws}"
KIT="${KIT:-$HOME/arc_compact_store_kit}"
PERC="${PERC:-$HOME/arc-perception}"
PERC_PY="${PERC_PY:-$HOME/arc_perception/.venv/bin/python}"
DB="$HOME/.ros/rtabmap.db"
BACKUPS="$WS/arc_backups"
SRC="source /opt/ros/jazzy/setup.bash && source $WS/install/setup.bash"

ICP_ARGS="--Icp/PointToPlane true --Icp/VoxelSize 0.05 --Icp/MaxCorrespondenceDistance 0.5 --Icp/Iterations 10 \
--Icp/Epsilon 0.001 --Icp/OutlierRatio 0.7 --Icp/CorrespondenceRatio 0.2 --Odom/ScanKeyFrameThr 0.4 \
--OdomF2M/ScanSubtractRadius 0.05 --OdomF2M/ScanMaxSize 15000 --Reg/Force3DoF true"
SLAM_ARGS="--Reg/Strategy 1 --Reg/Force3DoF true --Grid/Sensor 0 --Grid/RangeMin 0.2 --RGBD/NeighborLinkRefining true \
--Optimizer/GravitySigma 0 --Icp/PointToPlane true --Icp/VoxelSize 0.05 --Icp/MaxCorrespondenceDistance 0.5"
SLAM_ROS="--ros-args -r __ns:=/rtabmap -p use_sim_time:=true -p frame_id:=base_footprint -p subscribe_depth:=false \
-p subscribe_rgb:=false -p subscribe_scan:=true -p approx_sync:=true -r scan:=/scan -r odom:=/odom_icp"

G=$'\e[32m'; R=$'\e[31m'; Y=$'\e[33m'; B=$'\e[1m'; N=$'\e[0m'
ok() { echo "  ${G}[OK]${N}   $*"; }
bad() { echo "  ${R}[FAIL]${N} $*"; FAILS=$((FAILS + 1)); }
warn() { echo "  ${Y}[WARN]${N} $*"; }
FAILS=0

USE_TABS=1
if [[ "${DRY:-0}" == "1" ]] || ! command -v gnome-terminal >/dev/null; then USE_TABS=0; fi
STEP=0

# tab <title> <seconds to wait after opening> <command>
tab() {
  local title="$1" wait="$2" cmd="$3"
  STEP=$((STEP + 1))
  if [[ $USE_TABS -eq 1 ]]; then
    gnome-terminal --tab --title="$title" -- bash -c "$SRC; echo '== $title'; $cmd; echo; echo '[$title exited] press Enter to close'; read" &
    echo "  ${B}$STEP. $title${N} (tab opened; waiting ${wait}s)"
    sleep "$wait"
  else
    echo
    echo "${B}Terminal $STEP: $title${N}   (then wait about ${wait}s)"
    echo "$SRC && $cmd"
  fi
}

sim() {  # <rtabmap extra args>
  tab "1 Gazebo store" 10 "ros2 launch arc_store_sim store.launch.py world:=arc_store.sdf"
  tab "2 Robot description" 4 "export TURTLEBOT3_MODEL=burger && ros2 launch turtlebot3_gazebo robot_state_publisher.launch.py use_sim_time:=true"
  tab "3 Spawn + robot bridge" 6 "ros2 run ros_gz_sim create -name arc -file \$(ros2 pkg prefix turtlebot3_gazebo)/share/turtlebot3_gazebo/models/turtlebot3_burger/model.sdf -x 0.0 -y 0.0 -z 0.01 -Y 0.0 && ros2 run ros_gz_bridge parameter_bridge --ros-args -p config_file:=$WS/src/arc_store_sim/config/arc_store_burger_bridge.yaml -p use_sim_time:=true"
  tab "4 Lidar odometry (ICP)" 4 "ros2 run rtabmap_odom icp_odometry $ICP_ARGS --ros-args -p use_sim_time:=true -p frame_id:=base_footprint -p odom_frame_id:=icp_odom -p guess_frame_id:=odom -p publish_tf:=true -r scan:=/scan -r odom:=/odom_icp"
  tab "5 RTAB-Map" 6 "ros2 run rtabmap_slam rtabmap $1 $SLAM_ARGS $SLAM_ROS"
  tab "6 RViz" 3 "rviz2 -d $KIT/run/arc_nav.rviz --ros-args -p use_sim_time:=true"
}

do_check() {
  echo "${B}ARC pre-flight check${N}"
  [[ -f /opt/ros/jazzy/setup.bash ]] && ok "ROS 2 Jazzy" || bad "ROS 2 Jazzy not found"
  [[ -f "$WS/install/setup.bash" ]] && ok "workspace built ($WS)" || bad "$WS/install/setup.bash missing: colcon build --symlink-install"
  grep -q "Generated by arc_compact_store_kit" "$WS/install/arc_store_sim/share/arc_store_sim/worlds/arc_store.sdf" 2>/dev/null \
    && ok "installed world is the compact store" || bad "installed arc_store.sdf is not the compact store (run the store phase + build)"
  grep -q "frame_id: map" "$WS/src/arc_store_sim/config/item_locations.yaml" 2>/dev/null \
    && ok "item_locations.yaml in frame map" || bad "item_locations.yaml not in frame map"
  grep -q "aisle:" "$WS/src/arc_store_sim/config/item_locations.yaml" 2>/dev/null \
    && ok "items placed by aisle" || warn "items not placed by aisle yet: python3 $KIT/assign_items.py --write"
  [[ -f "$WS/src/arc_planner_claude/COLCON_IGNORE" || ! -d "$WS/src/arc_planner_claude" ]] \
    && ok "no duplicate arc_planner package" || bad "touch $WS/src/arc_planner_claude/COLCON_IGNORE"
  for f in ros_tools/auto_map.py ros_tools/check_frames.py ros_tools/item_markers.py run/arc_nav.rviz assign_items.py; do
    [[ -f "$KIT/$f" ]] && ok "kit: $f" || bad "kit file missing: $KIT/$f (unzip the latest kit/update)"
  done
  set +u; source /opt/ros/jazzy/setup.bash 2>/dev/null; source "$WS/install/setup.bash" 2>/dev/null; set -u
  for p in turtlebot3_gazebo ros_gz_sim ros_gz_bridge rtabmap_odom rtabmap_slam nav2_controller nav2_lifecycle_manager teb_local_planner arc_planner arc_behavior_tree arc_store_sim; do
    ros2 pkg prefix "$p" >/dev/null 2>&1 && ok "package $p" || bad "package $p not found"
  done
  [[ -f "$DB" ]] && ok "saved map $DB ($(du -h "$DB" | cut -f1)) -> './arc_up.sh nav' can reuse it" \
                 || warn "no saved map yet -> run './arc_up.sh map' first"
  if [[ -x "$PERC_PY" && -f "$PERC/ros/perception_bridge.py" ]]; then
    "$PERC_PY" -c "import rclpy, ultralytics, cv2" 2>/dev/null && ok "perception venv can import rclpy + ultralytics + cv2" \
      || bad "perception venv cannot import rclpy/ultralytics/cv2 ($PERC_PY)"
    [[ -f "$PERC/yolov8n.pt" ]] && ok "yolov8n.pt present" || bad "copy yolov8n.pt into $PERC"
  else
    warn "perception bridge not set up ($PERC/ros/perception_bridge.py or $PERC_PY missing): only needed for 'nav --perception'"
  fi
  ls /dev/video* >/dev/null 2>&1 && ok "camera device(s): $(ls /dev/video* | tr '\n' ' ')" || warn "no /dev/video* camera found"
  echo
  [[ $FAILS -eq 0 ]] && echo "${G}${B}Pre-flight passed.${N}" || echo "${R}${B}$FAILS problem(s) above.${N}"
}

do_stop() {
  for p in "gz sim" parameter_bridge icp_odometry rtabmap rtabmap_viz robot_state_publisher rviz2 controller_server \
           lifecycle_manager dijkstra_planner planned_path_to_teb person_assistant_bt arc_motion_gate person_state_input \
           shopping_manager item_markers.py auto_map.py perception_bridge.py; do
    pkill -f "$p" 2>/dev/null
  done
  sleep 1
  set +u; source /opt/ros/jazzy/setup.bash; set -u
  ros2 daemon stop >/dev/null 2>&1
  echo "All ARC processes stopped. (RTAB-Map saves its map to $DB when it is stopped.)"
}

case "${1:-}" in
  check) do_check ;;
  stop) do_stop ;;
  map)
    echo "${B}ARC mapping run${N}: new map, autonomous drive, then backup."
    [[ -f "$DB" ]] && mkdir -p "$BACKUPS" && cp "$DB" "$BACKUPS/rtabmap_before_remap_$(date +%Y%m%d_%H%M%S).db" \
      && echo "  previous map backed up to $BACKUPS"
    sim "-d"
    tab "7 Mapping drive" 1 "sleep 5 && python3 $KIT/ros_tools/auto_map.py && ros2 service call /rtabmap/set_mode_localization std_srvs/srv/Empty && echo && echo 'MAP DONE. Stop everything with ./arc_up.sh stop (RTAB-Map then saves the map), then run ./arc_up.sh nav'"
    ;;
  nav)
    [[ -f "$DB" ]] || { echo "No saved map at $DB: run './arc_up.sh map' first."; exit 1; }
    MODE="${2:-}"
    echo "${B}ARC navigation run${N}: saved map (localization only) + full stack. Input: ${MODE:---manual (person_state_input)}"
    mkdir -p "$BACKUPS" && cp "$DB" "$BACKUPS/rtabmap_latest.db"
    sim "--Mem/IncrementalMemory false --Mem/InitWMWithAllNodes true"
    tab "B1 TEB controller" 4 "ros2 run nav2_controller controller_server --ros-args --params-file $WS/src/arc_planner/config/teb_controller.yaml -r cmd_vel:=/cmd_vel_nav"
    tab "B2 Lifecycle manager" 5 "ros2 run nav2_lifecycle_manager lifecycle_manager --ros-args -r __node:=lifecycle_manager_controller -p use_sim_time:=true -p autostart:=true -p node_names:=\"['controller_server']\""
    tab "B3 Dijkstra planner" 3 "ros2 run arc_planner dijkstra_planner --ros-args -p use_sim_time:=true"
    tab "B4 Path to TEB" 2 "ros2 run arc_planner planned_path_to_teb --ros-args -p use_sim_time:=true"
    tab "B5 Behaviour tree + motion gate" 3 "ros2 launch arc_behavior_tree arc_bt_stack.launch.py"
    tab "B8 Store labels" 1 "python3 $KIT/ros_tools/item_markers.py"
    if [[ "$MODE" == "--perception" ]]; then
      tab "B6 Perception bridge (camera)" 3 "cd $PERC && $PERC_PY ros/perception_bridge.py --max-lost-s 4"
    else
      tab "B6 Person state (type 3 = LEAD, 1 = FOLLOW)" 2 "ros2 run arc_behavior_tree person_state_input"
    fi
    tab "B7 Shopping Manager" 1 "ros2 run arc_planner shopping_manager"
    tab "Check: map vs Gazebo truth" 1 "echo 'Press Enter when the robot is stopped:' && python3 $KIT/ros_tools/check_frames.py --model arc --samples 1"
    ;;
  *) sed -n '2,15p' "$0"; exit 0 ;;
esac
[[ $USE_TABS -eq 1 ]] && echo "Done opening tabs. ./arc_up.sh stop closes everything."
exit 0
