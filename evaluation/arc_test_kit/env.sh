# shellcheck shell=bash
# Source this in EVERY terminal that talks to the ARC simulation:
#   source ~/arc_test_kit/env.sh
# Keeps Gazebo transport and ROS 2 entirely on this laptop (loopback / shared memory),
# so Wi-Fi changes cannot cut the simulation off from ROS.
# 15 Oct 10:30: Wi-Fi loss broke the Gazebo bridge (multicast "Network is unreachable").
# 15 Oct 17:41: Wi-Fi reconnect broke ROS 2 discovery (/clock no longer seen) -> Fast DDS
#               is now pinned to 127.0.0.1 + shared memory by fastdds_localhost.xml.
_ARC_KIT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source /opt/ros/jazzy/setup.bash
source "$HOME/slam_ws/install/setup.bash"
export GZ_IP=127.0.0.1          # Gazebo transport always stays on this laptop
export RMW_IMPLEMENTATION=rmw_fastrtps_cpp
# Network mode, read from ~/.arc_net (written by ~/arc_pi/laptop/hil_mode.sh):
#   local (default, no file): ROS 2 on this laptop only, exactly as before.
#   hil: ROS 2 also on the one link to the Raspberry Pi (phone hotspot Wi-Fi or Ethernet cable, from
#        ~/arc_pi/hil.conf) and nothing else. Profile generated by hil_mode.sh at ~/.arc_hil/fastdds_hil.xml.
ARC_NET_MODE=local
[ -f "$HOME/.arc_net" ] && ARC_NET_MODE=$(tr -d '[:space:]' < "$HOME/.arc_net")
if [ "$ARC_NET_MODE" = hil ] && [ -f "$HOME/.arc_hil/fastdds_hil.xml" ]; then
  export ROS_AUTOMATIC_DISCOVERY_RANGE=SUBNET
  export FASTRTPS_DEFAULT_PROFILES_FILE="$HOME/.arc_hil/fastdds_hil.xml"
  export FASTDDS_DEFAULT_PROFILES_FILE="$HOME/.arc_hil/fastdds_hil.xml"
else
  ARC_NET_MODE=local
  export ROS_AUTOMATIC_DISCOVERY_RANGE=LOCALHOST
  export FASTRTPS_DEFAULT_PROFILES_FILE="$_ARC_KIT/fastdds_localhost.xml"
  export FASTDDS_DEFAULT_PROFILES_FILE="$_ARC_KIT/fastdds_localhost.xml"
fi
export ARC_NET_MODE
